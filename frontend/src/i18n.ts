const STRINGS: Record<Language, Record<Key, string>> = { en, id }

export type T = (key: Key, vars?: Record<string, string | number>) => string

export function translator(language: Language): T {
  return (key, vars) => {
    let text = STRINGS[language][key] ?? en[key]
    for (const [name, value] of Object.entries(vars ?? {})) text = text.replaceAll(`{${name}}`, String(value))
    return text
  }
}

export const tagKey = (tag: KeyTag) => `tag.${tag}` as Key
export const eventKey = (eventType: string) => `event.${eventType}` as Key
export const outcomeKey = (outcome: string) => `outcome.${outcome}` as Key
export const metricKey = (metricId: string) => `metric.${metricId}` as Key
export const hasKey = (key: string): key is Key => key in en
